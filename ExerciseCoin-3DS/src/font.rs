pub(crate) const GLYPH_W: i32 = 8; // cell advance per character (includes the font's built-in spacing)

pub(crate) fn draw_glyph(buf: &mut [u8], dw: i32, dh: i32, ch: char, x: i32, y: i32, scale: i32, c: (u8, u8, u8)) {
    let code = ch as u32;
    let g = if (0x20..0x80).contains(&code) { &FONT8X8[(code - 0x20) as usize] } else { return };
    for (row, bits) in g.iter().enumerate() {
        for col in 0..8 {
            if bits & (1 << col) != 0 {
                for sy in 0..scale { for sx in 0..scale {
                    crate::set_px(buf.as_mut_ptr(), dw, dh,
                        x + col * scale + sx, y + row as i32 * scale + sy, c.0, c.1, c.2);
                }}
            }
        }
    }
}

pub(crate) fn text_width(s: &str, scale: i32) -> i32 { s.chars().count() as i32 * GLYPH_W * scale }

pub(crate) fn draw_text(buf: &mut [u8], dw: i32, dh: i32, s: &str, mut x: i32, y: i32, scale: i32, c: (u8, u8, u8)) {
    for ch in s.chars() { draw_glyph(buf, dw, dh, ch, x, y, scale, c); x += GLYPH_W * scale; }
}

/// A cream Win95 caption box with centred dark text, sized to fit, centred on `cx` with its
/// top at `by`, drawn into a dw×dh ARGB buffer. `tail` adds the downward speech-bubble nub.
/// Mirrors the Windows `draw_caption` look.
pub(crate) fn draw_caption(buf: &mut [u8], dw: i32, dh: i32, text: &str, cx: i32, by: i32, tail: bool) {
    let p = buf.as_mut_ptr();
    let cream = (255u8, 251, 230); let ink = (20u8, 17, 15);
    let ts = 2;                          // text scale (16px tall)
    let th = 8 * ts;
    let tw = text_width(text, ts);
    let bw = (tw + 24).min(dw - 6);
    let bh = th + 16;
    let bx = (cx - bw / 2).clamp(3, (dw - bw - 3).max(3));
    let by = by.clamp(4, dh - bh - 10);
    for yy in by..by + bh { for xx in bx..bx + bw { crate::set_px(p, dw, dh, xx, yy, cream.0, cream.1, cream.2); } }
    for xx in bx..bx + bw { for t in 0..2 {
        crate::set_px(p, dw, dh, xx, by + t, ink.0, ink.1, ink.2);
        crate::set_px(p, dw, dh, xx, by + bh - 1 - t, ink.0, ink.1, ink.2);
    } }
    for yy in by..by + bh { for t in 0..2 {
        crate::set_px(p, dw, dh, bx + t, yy, ink.0, ink.1, ink.2);
        crate::set_px(p, dw, dh, bx + bw - 1 - t, yy, ink.0, ink.1, ink.2);
    } }
    if tail { for k in 0..8 { for xx in (cx - k)..(cx + k) { crate::set_px(p, dw, dh, xx, by + bh - 1 + k, cream.0, cream.1, cream.2); } } }
    draw_text(buf, dw, dh, text, bx + (bw - tw) / 2, by + (bh - th) / 2, ts, ink);
}
